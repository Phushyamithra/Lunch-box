/** Case-insensitive search across emoji keywords. */
export function searchIcons(query: string): readonly IconEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return ICON_LIBRARY;
  return ICON_LIBRARY.filter((entry) => entry.keywords.some((k) => k.includes(q)));
}
