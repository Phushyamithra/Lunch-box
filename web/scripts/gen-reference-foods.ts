/**
 * Writes supabase/migrations/0010_indian_foods.sql from the catalog.
 * Run: npx vite-node web/scripts/gen-reference-foods.ts
 * Re-running the SQL updates reference foods in place (by ref_code); your own
 * foods and every logged entry (snapshots) are untouched.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildReferenceFoods } from '../src/nutrition/reference/build';

const q = (v: string | null) => (v === null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null) => (v === null ? 'null' : String(v));
const foods = buildReferenceFoods();

const rows = foods.map(
  (f) =>
    `  (${q(f.code)}, ${q(f.name)}, ${q(f.aliases)}, ${q(f.category)}, ${q(f.diet)}, ${q(f.basis)}, ${q(JSON.stringify(f.portions))}::jsonb, ${n(f.kcal)}, ${n(f.protein)}, ${n(f.carbs)}, ${n(f.fat)}, ${n(f.fibre)}, ${n(f.sugar)}, ${n(f.sodium_mg)}, ${q(f.source)}, ${q(f.verification)}, ${q(f.source_url)}, ${q(f.notes)})`,
);

const sql = `-- Nutrition, stage 3: the Indian food catalog (${foods.length} foods).
-- GENERATED by web/scripts/gen-reference-foods.ts from web/src/nutrition/reference/*.
-- Do not edit by hand: change the catalog and regenerate.
--  * Ingredients: IFCT 2017 (NIN-ICMR) and USDA FoodData Central, per 100 g
--    as bought → verification 'official'.
--  * Dishes: computed from a typical home recipe → 'estimated' (the recipe
--    is in notes). Salt isn't counted, so dish sodium is null.
-- Shared rows (user_id null): everyone can read them, nobody can edit them
-- from the app. Safe to re-run: rows are matched by ref_code and updated.
-- Logged entries keep their own snapshot, so updating values here never
-- changes past days.

alter table public.foods
  add column if not exists ref_code  text,
  add column if not exists category  text,
  add column if not exists aliases   text not null default '',
  add column if not exists notes     text;

create unique index if not exists foods_ref_code on public.foods (ref_code) where user_id is null;

insert into public.foods
  (ref_code, name, aliases, category, diet, basis, portions, kcal, protein, carbs, fat, fibre, sugar, sodium_mg, source, verification, source_url, notes, user_id, captured_at)
select v.*, null::uuid, date '2026-10-19'
from (values
${rows.join(',\n')}
) as v(ref_code, name, aliases, category, diet, basis, portions, kcal, protein, carbs, fat, fibre, sugar, sodium_mg, source, verification, source_url, notes)
on conflict (ref_code) where user_id is null do update set
  name = excluded.name, aliases = excluded.aliases, category = excluded.category, diet = excluded.diet,
  basis = excluded.basis, portions = excluded.portions, kcal = excluded.kcal, protein = excluded.protein,
  carbs = excluded.carbs, fat = excluded.fat, fibre = excluded.fibre, sugar = excluded.sugar,
  sodium_mg = excluded.sodium_mg, source = excluded.source, verification = excluded.verification,
  source_url = excluded.source_url, notes = excluded.notes, captured_at = excluded.captured_at,
  updated_at = now();
`;

const out = resolve(__dirname, '../../supabase/migrations/0010_indian_foods.sql');
writeFileSync(out, sql);
console.log(`wrote ${foods.length} foods to ${out}`);
